DROP DATABASE IF EXISTS shopthoitrang;
CREATE DATABASE shopthoitrang CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE shopthoitrang;

-- Người dùng (Quản lý / Nhân viên bán hàng). Mật khẩu lưu dạng băm SHA-256
CREATE TABLE Users (
    Id          INT AUTO_INCREMENT PRIMARY KEY,
    Username    VARCHAR(50)  NOT NULL UNIQUE,
    Password    CHAR(64)     NOT NULL,
    FullName    VARCHAR(100) NOT NULL,
    Role        VARCHAR(20)  NOT NULL DEFAULT 'Staff',   -- 'Admin' | 'Staff'
    IsActive    BOOLEAN      NOT NULL DEFAULT TRUE,
    CreatedAt   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_Users_Role CHECK (Role IN ('Admin','Staff'))
);

-- Danh mục sản phẩm
CREATE TABLE Categories (
    Id           INT AUTO_INCREMENT PRIMARY KEY,
    CategoryName VARCHAR(100) NOT NULL UNIQUE,
    Description  VARCHAR(500) NULL,
    IsActive     BOOLEAN NOT NULL DEFAULT TRUE
);

-- Sản phẩm
CREATE TABLE Products (
    Id          INT AUTO_INCREMENT PRIMARY KEY,
    ProductCode VARCHAR(50)   NOT NULL UNIQUE,
    Name        VARCHAR(200)  NOT NULL,
    CategoryId  INT           NOT NULL,
    CostPrice   DECIMAL(15,0) NOT NULL DEFAULT 0,   -- giá nhập
    UnitPrice   DECIMAL(15,0) NOT NULL DEFAULT 0,   -- giá bán
    Unit        VARCHAR(20)   NOT NULL DEFAULT 'chiếc',
    ImagePath   VARCHAR(500)  NULL,
    IsActive    BOOLEAN       NOT NULL DEFAULT TRUE,
    CreatedAt   DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt   DATETIME      NULL,
    CONSTRAINT FK_Products_Categories FOREIGN KEY (CategoryId) REFERENCES Categories(Id),
    CONSTRAINT CK_Products_Price CHECK (CostPrice >= 0 AND UnitPrice >= 0)
);

-- Tồn kho (mỗi sản phẩm 1 dòng). MinStock = ngưỡng cảnh báo tồn thấp
CREATE TABLE Inventory (
    Id              INT AUTO_INCREMENT PRIMARY KEY,
    ProductId       INT NOT NULL UNIQUE,
    QuantityInStock INT NOT NULL DEFAULT 0,
    MinStock        INT NOT NULL DEFAULT 5,
    LastUpdated     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_Inventory_Products FOREIGN KEY (ProductId) REFERENCES Products(Id),
    CONSTRAINT CK_Inventory_Qty CHECK (QuantityInStock >= 0)
);

-- Lịch sử nhập / xuất / điều chỉnh kho
CREATE TABLE InventoryLogs (
    Id         INT AUTO_INCREMENT PRIMARY KEY,
    ProductId  INT NOT NULL,
    ChangeQty  INT NOT NULL,                 -- dương: nhập, âm: xuất
    StockAfter INT NOT NULL,
    Note       VARCHAR(255) NULL,
    UserId     INT NULL,
    CreatedAt  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_Logs_Products FOREIGN KEY (ProductId) REFERENCES Products(Id),
    CONSTRAINT FK_Logs_Users    FOREIGN KEY (UserId)    REFERENCES Users(Id)
);

-- Khách hàng
CREATE TABLE Customers (
    Id           INT AUTO_INCREMENT PRIMARY KEY,
    CustomerName VARCHAR(100) NOT NULL,
    Phone        VARCHAR(20)  NULL UNIQUE,
    Email        VARCHAR(100) NULL,
    Address      VARCHAR(500) NULL,
    IsActive     BOOLEAN NOT NULL DEFAULT TRUE,
    CreatedAt    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Hóa đơn / đơn hàng
CREATE TABLE Orders (
    Id              INT AUTO_INCREMENT PRIMARY KEY,
    OrderCode       VARCHAR(30)   NOT NULL UNIQUE,
    OrderDate       DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CustomerId      INT           NULL,               -- NULL = khách lẻ
    UserId          INT           NOT NULL,           -- nhân viên lập
    SubTotal        DECIMAL(15,0) NOT NULL DEFAULT 0, -- tổng tiền hàng
    DiscountPercent DECIMAL(5,2)  NOT NULL DEFAULT 0,
    DiscountAmount  DECIMAL(15,0) NOT NULL DEFAULT 0, -- tổng tiền giảm (gồm cả % và VNĐ)
    VatPercent      DECIMAL(5,2)  NOT NULL DEFAULT 0,
    VatAmount       DECIMAL(15,0) NOT NULL DEFAULT 0,
    TotalAmount     DECIMAL(15,0) NOT NULL DEFAULT 0, -- khách phải trả
    PaymentMethod   VARCHAR(30)   NOT NULL DEFAULT 'Tiền mặt',
    Status          VARCHAR(20)   NOT NULL DEFAULT 'Paid',  -- 'Paid' | 'Cancelled'
    PrintedAt       DATETIME      NULL,
    CONSTRAINT FK_Orders_Customers FOREIGN KEY (CustomerId) REFERENCES Customers(Id),
    CONSTRAINT FK_Orders_Users     FOREIGN KEY (UserId)     REFERENCES Users(Id),
    CONSTRAINT CK_Orders_Payment CHECK (PaymentMethod IN ('Tiền mặt','Thẻ ngân hàng','Chuyển khoản')),
    CONSTRAINT CK_Orders_Status  CHECK (Status IN ('Paid','Cancelled'))
);

-- Chi tiết hóa đơn
CREATE TABLE OrderItems (
    Id        INT AUTO_INCREMENT PRIMARY KEY,
    OrderId   INT           NOT NULL,
    ProductId INT           NOT NULL,
    Quantity  INT           NOT NULL,
    UnitPrice DECIMAL(15,0) NOT NULL,   -- giá bán tại thời điểm bán
    CostPrice DECIMAL(15,0) NOT NULL,   -- giá vốn tại thời điểm bán (tính lợi nhuận)
    LineTotal DECIMAL(15,0) NOT NULL,
    CONSTRAINT FK_Items_Orders   FOREIGN KEY (OrderId)   REFERENCES Orders(Id) ON DELETE CASCADE,
    CONSTRAINT FK_Items_Products FOREIGN KEY (ProductId) REFERENCES Products(Id),
    CONSTRAINT CK_Items_Qty CHECK (Quantity > 0)
);

CREATE INDEX IX_Orders_Date ON Orders(OrderDate);

